// model.js —— 情绪动力学 v4（2026-11-02）
//
// 基准层：中科院 PAD 量表的 14 种情绪（Wang et al. 2023, JAMDSM 17(5), Table 2），
//   原值区间约 ±4，这里统一除以 4 归一化到 -1…1，方便和 PAD 场直接相乘。
//   喜悦 / 乐观 / 放松 / 惊讶 / 温和 / 依赖 / 无聊 / 悲伤 / 恐惧 / 焦虑 / 轻蔑 / 厌恶 / 怨恨 / 敌意
//
// 派生层（不占基准，由相干矩阵合成，语义上更稳）：
//   心疼  ≈ 悲伤（共情） + 温和/依赖（联结） + 怨恨（保护性成分）
//   吃醋  ≈ 焦虑（怕失去） + 敌意（被侵犯），权重受关系权力调制
//   沮丧  ≈ 悲伤 + 无聊 的低唤醒塌缩
//
// 三层分工：PAD 场管动力学（注入/弛豫/相干），OCC 评估管区分（指向谁、未来还是现在），
// 14 个离散标签管可解释读出。

const clamp = (x, lo, hi) => Math.max(lo, Math.min(hi, x))
const 圆 = (x, n = 3) => Math.round(x * 10 ** n) / 10 ** n

