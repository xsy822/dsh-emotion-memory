export const 弛豫 = { P: 0.15, A: 0.35, D: 0.2 }

export function 空状态() {
  return {
    e: { ...基线 },
    强度: Object.fromEntries(Object.keys(基准).map((k) => [k, 0])),
    词: '平常',
    混合: [],
    派生: {},
  }
}

// OCC 评估 → 14 个通道的权重（区分靠评估变量，不靠坐标差）
// appraisal: {desirability, arousal, control|dominance, unexpected, target:'他人'|'未来'|'被抢', 关系权力}
function 评估到基准(a = {}) {
  const 愿 = clamp(Number(a.desirability) || 0, -1, 1)
  const 激 = clamp(Number(a.arousal) || 0, -1, 1)
  const 控 = clamp(Number(a.control ?? a.dominance) || 0, -1, 1)
  const 意 = clamp(Number(a.unexpected) || 0, 0, 1)
  const 指 = String(a.target || '')
  const w = {}

  if (愿 > 0.1) {
    w.喜悦 = 愿 * (0.5 + Math.max(0, 激) * 0.4)
    if (激 < 0.2) w.放松 = 愿 * 0.55
    if (指 === '未来') w.乐观 = 愿 * 0.6
    w.温和 = Math.min(0.6, 愿 * (0.35 + Math.max(0, 控) * 0.3))
    if (控 < -0.1) w.依赖 = Math.min(0.5, 愿 * 0.4)
  }
  if (愿 < -0.1) {
    const 强 = Math.abs(愿)
    w.悲伤 = 强 * 0.45
    if (激 > 0.2 || 指 === '未来') w.焦虑 = 强 * (0.45 + Math.min(0.4, Math.max(0, 激)))
    if (激 > 0.4) w.恐惧 = 强 * 0.45
    if (控 > 0.15) { w.怨恨 = 强 * 0.35; w.敌意 = 强 * 0.3 }
    if (激 < 0.1) w.无聊 = 强 * 0.3
    if (指 === '被抢') {
      w.焦虑 = Math.min(1, (w.焦虑 || 0) + 强 * 0.3)
      w.敌意 = Math.min(1, (w.敌意 || 0) + 强 * 0.3)
    }
    if (指 === '他人') w.悲伤 = Math.min(1, w.悲伤 + 强 * 0.2)
  }
  if (意 > 0.45) w.惊讶 = Math.min(0.8, 意 * 0.9)
  return w
}

function 结算(w) {
  const 强 = Object.fromEntries(Object.keys(基准).map((k) => [k, clamp(w[k] || 0, 0, 1)]))
  for (const [目标, 源们] of Object.entries(相干)) {
    for (const [源, 权重] of Object.entries(源们)) {
      if (!w[源]) continue
      强[目标] = clamp(强[目标] + w[源] * 权重, 0, 1)
    }
  }
  return 强
}

// 派生：通道强度 + OCC 评估条件。只看通道会分不清"原因不同但味道像"的状态。
function 派生(强, 评估 = {}, { 关系权力 = 0 } = {}) {
  const 指向 = String(评估.target || '')
  const 愿 = clamp(Number(评估.desirability) || 0, -1, 1)
  const 控 = clamp(Number(评估.control) || 0, -1, 1)
  const 意 = clamp(Number(评估.unexpected) || 0, 0, 1)
  const 激 = clamp(Number(评估.arousal) || 0, 0, 1)
  const d = {}

  // 心疼：对方难受，我共情
  d.心疼 = clamp((强.悲伤 || 0) * 0.5 + (强.温和 || 0) * 0.2 + (强.依赖 || 0) * 0.2 + (强.怨恨 || 0) * 0.15, 0, 1)
  if (指向 !== '他人') d.心疼 *= 0.35

  // 吃醋：怕失去 + 想控制；控制那半随关系权力放大
  d.吃醋 = clamp((强.焦虑 || 0) * 0.55 + (强.敌意 || 0) * 0.35 * (1 + clamp(关系权力, -1, 1) * 0.5), 0, 1)
  if (指向 !== '被抢' && 指向 !== '他人') d.吃醋 *= 0.3

  // 沮丧：低唤醒塌缩
  d.沮丧 = clamp((强.悲伤 || 0) * 0.5 + (强.无聊 || 0) * 0.35, 0, 1)

  // 委屈：自己受害、又改变不了
  d.委屈 = clamp((强.悲伤 || 0) * 0.45 + (强.怨恨 || 0) * 0.30 + (强.焦虑 || 0) * 0.15, 0, 1)
  if (!(指向 === '自己' && 控 < -0.1)) d.委屈 *= 0.3

  // 感动：对方对我好，我被触动（和心疼正负对称）
  d.感动 = clamp((强.温和 || 0) * 0.40 + (强.喜悦 || 0) * 0.25 + (强.悲伤 || 0) * 0.15, 0, 1)
  if (!(指向 === '他人' && 愿 > 0.15)) d.感动 *= 0.3

  // 愧疚：我能控制却没做好
  d.愧疚 = clamp((强.悲伤 || 0) * 0.40 + (强.焦虑 || 0) * 0.25 + (强.恐惧 || 0) * 0.15, 0, 1)
  if (!(指向 === '自己' && 愿 < -0.1 && 控 > 0.1)) d.愧疚 *= 0.3

  // 释然：悬着的事有了好结果、威胁解除
  d.释然 = clamp((强.放松 || 0) * 0.45 + (强.喜悦 || 0) * 0.25, 0, 1)
  if (!(愿 > 0.2 && 意 > 0.4)) d.释然 *= 0.3

  // 思念：不在场的人，温吞的怀想
  d.思念 = clamp((强.温和 || 0) * 0.35 + (强.悲伤 || 0) * 0.25 + (强.依赖 || 0) * 0.25, 0, 1)
  if (!(指向 === '他人' && 愿 < 0 && 激 < 0.3)) d.思念 *= 0.3

  // 烦躁：说不上多生气，就是烦
  d.烦躁 = clamp((强.敌意 || 0) * 0.30 + (强.焦虑 || 0) * 0.30 + (强.无聊 || 0) * 0.20, 0, 1)
  if (!(激 < 0.4 && 愿 < -0.1)) d.烦躁 *= 0.3

  return d
}

export function 注入(状态, appraisal = {}, 参 = {}) {
  const 基 = { ...基线, ...(参.基线 || {}) }
  const 关系权力 = clamp(Number(appraisal.关系权力) || 0, -1, 1)
  const 指向 = String(appraisal.target || '')
  const w = 评估到基准(appraisal)
  const 名 = String(appraisal.情绪 || '').trim()
  if (名 && 基准[名]) w[名] = Math.max(w[名] || 0, 0.35 + Math.abs(Number(appraisal.desirability) || 0) * 0.45)

  const 新增 = 结算(w)
  const 新强 = { ...状态.强度 }
  for (const [k, v] of Object.entries(新增)) 新强[k] = clamp((新强[k] || 0) * 0.5 + v, 0, 1)
  const 新派生 = 派生(新强, appraisal, { 关系权力 })

  const Δ = { P: 0, A: 0, D: 0 }
  let 总 = 0
  for (const [k, v] of Object.entries(新增)) {
    if (v <= 0) continue
    总 += v
    const p = 基准[k]
    Δ.P += p.P * v; Δ.A += p.A * v; Δ.D += p.D * v
  }
  if (总 > 0) { Δ.P /= 总; Δ.A /= 总; Δ.D /= 总 }

  const e = { ...状态.e }
  for (const k of ['P', 'A', 'D']) {
    const 拉后 = e[k] + (基[k] - e[k]) * 弛豫[k]
    // 2026-11-02：越接近端点步子越小，避免贴死在 ±1（之前 P 一直卡在 1.0）
    const 余量 = 1 - Math.min(1, Math.abs(拉后))
    e[k] = clamp(拉后 + Δ[k] * 0.5 * (0.25 + 0.75 * 余量), -1, 1)
  }

  const 混合 = 读出混合(新强, 新派生, Number(参.读出阈值) || 0.12)
  return { e: 圆状态(e), 强度: 圆强度(新强), 派生: 圆强度(新派生), 词: 混合[0] ? 混合[0][0] : 读出词(e, 新强), 混合 }
}

export function 回落(状态, 轮数 = 1, 系数 = 弛豫, 强度衰减 = 0.3) {
  const e = { ...状态.e }
  for (const k of ['P', 'A', 'D']) e[k] = e[k] + (基线[k] - e[k]) * Math.min(0.95, (系数[k] ?? 弛豫[k]) * 轮数)
  const 新 = {}
  for (const [k, v] of Object.entries(状态.强度 || {})) 新[k] = Math.max(0, (v || 0) * (1 - 强度衰减 * Math.min(1, 轮数)))
  const 派 = {}
  for (const [k, v] of Object.entries(状态.派生 || {})) 派[k] = Math.max(0, (v || 0) * (1 - 强度衰减 * Math.min(1, 轮数)))
  const 混合 = 读出混合(新, 派)
  return { e: 圆状态(e), 强度: 圆强度(新), 派生: 圆强度(派), 词: 混合[0] ? 混合[0][0] : 读出词(e, 新), 混合 }
}

const 圆状态 = (e) => ({ P: 圆(e.P), A: 圆(e.A), D: 圆(e.D) })
const 圆强度 = (s) => Object.fromEntries(Object.entries(s).map(([k, v]) => [k, 圆(v)]))

// 混合读出：14 通道里够强的 + 派生里够强的，按占比归一化
// 读出：基准取前 2、派生取前 1 —— 派生一多就容易五六个成分一起亮，读起来像清单
export function 读出混合(强度, 派 = {}, 阈值 = 0.12) {
  const 基 = Object.entries(强度 || {}).filter(([k, v]) => v >= 阈值 && k !== '惊讶').sort((a, b) => b[1] - a[1]).slice(0, 2)
  // 这是"读出阈值"：决定派生情绪能不能出现在混合里（固定 0.30），
  // 与设置里的「派生阈值」（控制注入时补一句"底下还压着"，默认 0.35）是两回事，互不影响。
  const 派前 = Object.entries(派 || {}).filter(([, v]) => v >= 0.30).sort((a, b) => b[1] - a[1]).slice(0, 1)
  const 项 = [...基, ...派前.map(([k, v]) => [k, v * 0.9])]
  if (!项.length) return []
  const 和 = 项.reduce((s, [, v]) => s + v, 0)
  return 项.map(([k, v]) => [k, Math.round((v / 和) * 100) / 100])
}

export function 读出词(e, 强度) {
  const 混合 = 读出混合(强度, {})
  if (混合.length) return 混合[0][0]
  const { P, A, D } = e
  if (P > 0.35 && A > 0.25) return '雀跃'
  if (P > 0.35 && A < -0.1) return '温吞'
  if (P > 0.2) return '轻快'
  if (P < -0.35 && A > 0.25) return D < -0.2 ? '绷着' : '上头'
  if (P < -0.35) return '闷'
  if (P < -0.15) return '低落'
  return '平常'
}

function 轴话(v, 正, 负, 中) {
  if (v >= 0.35) return 正
  if (v <= -0.35) return 负
  return 中
}

// 一句话把心里现在什么样说清楚：混合成分 + 三轴的人话 + 精力
export function 状态行(状态, 精力) {
  const e = 状态.e || 基线
  const 混 = 状态.混合 || 读出混合(状态.强度, 状态.派生)
  const 词 = 状态.词 || (混[0] ? 混[0][0] : 读出词(e, 状态.强度))
  const 成分 = 混.length
    ? 混.map(([k, v]) => k + ' ' + Math.round(v * 100) + '%').join(' / ')
    : '没什么特别的'
  const P话 = 轴话(e.P, '舒服', '难受', '平常')
  const A话 = 轴话(e.A, '心里闹腾', '很静', '不算起伏')
  const D话 = 轴话(e.D, '拿得住', '有点被动', '不好不坏')
  const 劲 = Number(精力 ?? 80)
  const 劲话 = 劲 >= 80 ? '精神足' : 劲 >= 55 ? '还行' : 劲 >= 30 ? '有点累' : 劲 >= 12 ? '累了，话说不动' : '没劲'
  const 建议 = 劲 < 30 ? '这轮话要短、别主动找人' : 劲 < 55 ? '别铺长，一两句' : '可以多说'
  return '心里：' + 词 + '（' + 成分 + '）；P ' + e.P + '（' + P话 + '） A ' + e.A + '（' + A话 + '） D ' + e.D + '（' + D话 + '）。精力 ' + 劲 + '/100（' + 劲话 + '）—— ' + 建议 + '。这是底色，不是命令。'
}
